/** Count the published archive by kind from the real files and write
 *  archive-summary.mjs. Nothing here is typed in by hand.
 *
 *    node src/civic-ui/build-summary.mjs            write the module
 *    node src/civic-ui/build-summary.mjs --check    exit 1 if the module is out of date
 *
 *  It uses the same buildArchive() as archive.html, so the home figure and the
 *  archive page count the same rows, in and out of the poll blackout.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { ARCHIVE_FILES, ARCHIVE_KINDS, buildArchive } from "../lib/archive-model.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const PUBLIC = resolve(HERE, "../../public");
const TARGET = join(HERE, "archive-summary.mjs");

const read = (path) => JSON.parse(readFileSync(join(PUBLIC, path), "utf8"));
const has = (path) => existsSync(join(PUBLIC, path));

export function summarize() {
  const manifest = read("data/manifest.json");
  const docs = {};
  const inputs = {};
  for (const [id, path] of Object.entries(ARCHIVE_FILES)) {
    if (id === "monitorHistory" && !has(path)) continue;
    if (id === "monitorLatest" && (has(ARCHIVE_FILES.monitorHistory) || !has(path))) continue;
    docs[id] = read(path);
    const name = path.replace(/^\/data\//, "");
    if (path.startsWith("/data/")) inputs[name] = manifest.files?.[name]?.sha256 ?? null;
  }
  const tally = (blackout) => {
    // archive.html does not load polls.json at all during the blackout.
    const { rows, held } = buildArchive(blackout ? { ...docs, polls: undefined } : docs, { blackout });
    const counts = Object.fromEntries(Object.keys(ARCHIVE_KINDS).map((id) => [id, 0]));
    for (const row of rows) counts[row.kind] += 1;
    return { total: rows.length, held, counts };
  };
  return {
    inputs,
    stats_generated_at: docs.stats?.generated_at ?? null,
    labels: { ...ARCHIVE_KINDS },
    open: tally(false),
    blackout: tally(true),
  };
}

function render(summary, countedAt) {
  return `// Generated by src/civic-ui/build-summary.mjs from public/data and public/observations.
// Do not edit by hand: run \`node src/civic-ui/build-summary.mjs\` after the data changes.
export const ARCHIVE_SUMMARY = Object.freeze(${JSON.stringify({ counted_at: countedAt, ...summary }, null, 2)});
`;
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const summary = summarize();
  let current = null;
  if (existsSync(TARGET)) {
    const { ARCHIVE_SUMMARY } = await import(`${pathToFileURL(TARGET).href}?t=${Date.now()}`);
    const { counted_at: _countedAt, ...rest } = ARCHIVE_SUMMARY;
    current = rest;
  }
  const fresh = current && same(current, summary);
  if (process.argv.includes("--check")) {
    console.log(JSON.stringify({ upToDate: Boolean(fresh), total: summary.open.total, counts: summary.open.counts }));
    process.exit(fresh ? 0 : 1);
  }
  if (!fresh) {
    const now = new Date(Date.now() + 8 * 3600 * 1000).toISOString().replace(/\.\d+Z$/, "+08:00");
    writeFileSync(TARGET, render(summary, now), "utf8");
  }
  console.log(JSON.stringify({ written: !fresh, total: summary.open.total, held_in_blackout: summary.blackout.held, counts: summary.open.counts }));
}
